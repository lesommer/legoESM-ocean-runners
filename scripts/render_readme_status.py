#!/usr/bin/env python3
"""Render the README status block from project_status.md.

project_status.md ("Template test status" table) is the single source of
truth for per-template status. The README carries only a generated
category-count summary of it, between BEGIN/END markers; this script is
the only thing allowed to write that block.

Checks enforced (all can fail — that is the point):
  1. Status vocabulary: run-tested | smoke-tested | init-only | structural
  2. Template parity: every templates/<category>/<name>.yaml has exactly
     one row in the status table, and every row has a template file.

Modes:
  --write   rewrite the README block (default)
  --check   exit 1 with fix instructions if the block is stale

Usage:
  python scripts/render_readme_status.py            # write
  python scripts/render_readme_status.py --check   # CI gate
"""

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_STATUS = REPO_ROOT / "project_status.md"
DEFAULT_README = REPO_ROOT / "README.md"
TEMPLATES_DIR = REPO_ROOT / "templates"

STATUS_KEYWORDS = ("run-tested", "smoke-tested", "init-only", "structural")

BEGIN_MARKER = (
    "<!-- BEGIN status-summary: generated by scripts/render_readme_status.py;"
    " DO NOT EDIT -->"
)
END_MARKER = "<!-- END status-summary -->"

_ROW_RE = re.compile(
    r"^\|\s*`(?P<category>[^`]+)`\s*\|"
    r"\s*`(?P<template>[^`]+)`\s*\|"
    r"\s*(?P<status>[a-z-]+)\s*\|"
)


class StatusError(Exception):
    """Raised when project_status.md or templates/ are inconsistent."""


def parse_status_table(status_path: Path) -> list[dict]:
    """Parse the Template test status table rows from project_status.md."""
    rows: list[dict] = []
    in_table = False
    seen: set[str] = set()
    for line in status_path.read_text().splitlines():
        if line.strip() == "## Template test status":
            in_table = True
            continue
        if in_table and line.startswith("## ") and "Template test status" not in line:
            break
        if not in_table or not line.startswith("|"):
            continue
        m = _ROW_RE.match(line)
        if not m:
            # separator/header rows are fine
            if re.match(r"^\|[\s:|-]+\|$", line) or line.startswith(
                "| Category | Template |"
            ):
                continue
            raise StatusError(
                f"project_status.md: unparsable table row: {line!r}\n"
                "Expected: | `category/` | `template` | status | receipt |"
            )
        status = m.group("status")
        if status not in STATUS_KEYWORDS:
            raise StatusError(
                f"project_status.md: template {m.group('template')!r} has "
                f"unknown status {status!r}; allowed: {', '.join(STATUS_KEYWORDS)}"
            )
        key = f"{m.group('category').rstrip('/')}/{m.group('template')}"
        if key in seen:
            raise StatusError(
                f"project_status.md: duplicate status row for {key}"
            )
        seen.add(key)
        rows.append(
            {"category": m.group("category").rstrip("/"),
             "template": m.group("template"),
             "status": status}
        )
    if not rows:
        raise StatusError(
            f"project_status.md: no rows parsed from the "
            "'Template test status' table"
        )
    return rows


def check_template_parity(rows: list[dict], templates_dir: Path) -> None:
    """Every templates/<category>/<name>.yaml must have exactly one row."""
    on_disk = {
        f"{p.parent.name}/{p.stem}" for p in templates_dir.glob("*/*.yaml")
    }
    in_table = {f"{r['category']}/{r['template']}" for r in rows}
    missing = sorted(on_disk - in_table)
    ghost = sorted(in_table - on_disk)
    if missing:
        raise StatusError(
            "templates without a project_status.md status row "
            "(add a row to the Template test status table):\n  "
            + "\n  ".join(missing)
        )
    if ghost:
        raise StatusError(
            "status rows without a template file (remove the row or add "
            "the template):\n  " + "\n  ".join(ghost)
        )


def render_block(rows: list[dict]) -> str:
    """Render the generated README block (category counts)."""
    order: list[str] = []
    counts: dict[str, dict[str, int]] = {}
    for r in rows:
        cat = r["category"]
        if cat not in counts:
            counts[cat] = {k: 0 for k in STATUS_KEYWORDS}
            counts[cat]["total"] = 0
            order.append(cat)
        counts[cat][r["status"]] += 1
        counts[cat]["total"] += 1

    lines = [BEGIN_MARKER, "", "Template status by category (per-template",
             "receipts and history live in",
             "[project_status.md](project_status.md)):", ""]
    for cat in order:
        c = counts[cat]
        parts = [f"{c[k]} {k}" for k in STATUS_KEYWORDS if c[k]]
        noun = "template" if c["total"] == 1 else "templates"
        lines.append(
            f"- `{cat}/` — {c['total']} {noun}: " + ", ".join(parts)
        )
    lines += ["", END_MARKER]
    return "\n".join(lines)


def split_readme(readme_text: str) -> tuple[str, str, str]:
    """Split README into (before, generated, after) around the markers."""
    b = readme_text.find(BEGIN_MARKER)
    e = readme_text.find(END_MARKER)
    if b == -1 or e == -1:
        raise StatusError(
            "README.md: generated status block not found. Add:\n"
            f"  {BEGIN_MARKER}\n  (block)\n  {END_MARKER}"
        )
    return (
        readme_text[:b],
        readme_text[b:e + len(END_MARKER)],
        readme_text[e + len(END_MARKER):],
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="fail (exit 1) if the README block is stale")
    ap.add_argument("--project-status", type=Path, default=DEFAULT_STATUS)
    ap.add_argument("--readme", type=Path, default=DEFAULT_README)
    ap.add_argument("--templates-dir", type=Path, default=TEMPLATES_DIR)
    args = ap.parse_args()

    try:
        rows = parse_status_table(args.project_status)
        check_template_parity(rows, args.templates_dir)
        block = render_block(rows)
        readme_text = args.readme.read_text()
        _, current, _ = split_readme(readme_text)
    except StatusError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    if current.strip() == block.strip():
        print("README status block up to date "
              f"({len(rows)} templates, {len(set(r['category'] for r in rows))} categories).")
        return 0

    if args.check:
        print("ERROR: README status block is stale.", file=sys.stderr)
        print("Fix: python scripts/render_readme_status.py --write",
              file=sys.stderr)
        print("and commit it together with the project_status.md change.",
              file=sys.stderr)
        return 1

    _, _, after = split_readme(readme_text)
    # normalize: keep exactly the block + surrounding newlines
    before = readme_text[:readme_text.find(BEGIN_MARKER)]
    args.readme.write_text(before + block + after)
    print(f"README status block rewritten ({len(rows)} templates).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
